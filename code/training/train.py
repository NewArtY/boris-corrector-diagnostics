import sys
import time
import json

import numpy as np
import torch
from torch.utils.data import TensorDataset, DataLoader

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from common import set_global_seed, SEED, CHECKPOINT_DIR, get_logger, log_run_params
from training.dataset_generation import (build_and_save_all, load_combined_dataset,
                                          build_and_save_corrector_dataset, load_corrector_dataset)
from models.pinn_symplectic import build_model as build_pinn, LR as LR_PINN
from models.hnn import build_model as build_hnn, LR as LR_HNN
from models.sympnet import build_model as build_symp, LR as LR_SYMP
from models.boris_corrector import build_model as build_bc, LR as LR_BC
from models.boris import boris_step
from fields import UniformField, DipoleField, StochasticField

logger = get_logger("train")

EPOCHS = 200
BATCH_SIZE = 1024
DEVICE = "cpu"

TRAIN_FIELDS = {
    "uniform": UniformField(B0=1.0),
    "dipole": DipoleField(B0=1.0, r0=5.0),
    "stochastic": StochasticField(B0=1.0, eps=0.15, omega=0.5, seed=SEED),
}


def to_tensor(x):
    return torch.tensor(x, dtype=torch.float32, device=DEVICE)


def vectorized_boris_step(r, v, B, dt, q=-1.0, m=1.0):
    """Fully vectorized Boris step for arrays of shape (N,3) / (N,) dt,
    with E=0 (fields already sampled into B). Used to precompute the Boris
    baseline for the whole Boris+Corrector training set efficiently."""
    dt = dt[:, None]
    qmdt2 = 0.5 * q * dt / m
    v_minus = v  # E=0
    t_vec = qmdt2 * B
    t_mag2 = np.sum(t_vec * t_vec, axis=-1, keepdims=True)
    s_vec = 2.0 * t_vec / (1.0 + t_mag2)
    v_prime = v_minus + np.cross(v_minus, t_vec)
    v_plus = v_minus + np.cross(v_prime, s_vec)
    v_new = v_plus  # E=0
    r_new = r + v_new * dt
    return r_new, v_new


def make_loader(data, batch_size=BATCH_SIZE, shuffle=True):
    ds = TensorDataset(
        to_tensor(data["r"]), to_tensor(data["v"]), to_tensor(data["B"]),
        to_tensor(data["dt"]), to_tensor(data["r_next"]), to_tensor(data["v_next"]),
        to_tensor(data["drdt"]), to_tensor(data["dvdt"]),
    )
    return DataLoader(ds, batch_size=batch_size, shuffle=shuffle)


def train_pinn(train_data, val_data, epochs=EPOCHS):
    logger.info("=== Training PINN-symplectic ===")
    set_global_seed(SEED)
    model = build_pinn().to(DEVICE)
    opt = torch.optim.Adam(model.parameters(), lr=LR_PINN)
    loader = make_loader(train_data)
    history = []
    for epoch in range(epochs):
        model.train()
        epoch_loss = 0.0
        n_batches = 0
        for r, v, B, dt, r_next, v_next, drdt, dvdt in loader:
            opt.zero_grad()
            r_pred, v_pred = model(r, v, B, dt)
            loss, parts = model.physics_loss(r, v, r_pred, v_pred, r_next, v_next)
            loss.backward()
            opt.step()
            epoch_loss += loss.item()
            n_batches += 1
        avg_loss = epoch_loss / n_batches
        history.append(avg_loss)
        if epoch % 50 == 0 or epoch == epochs - 1:
            logger.info(f"[PINN-symplectic] epoch {epoch:4d}/{epochs}  loss={avg_loss:.6e}")
    return model, history


