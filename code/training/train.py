"""
train.py
========
Trains all four neural integrator models (PINN-symplectic, HNN, SympNet,
Boris+Corrector) on the reference Boris trajectory datasets generated by
dataset_generation.py, and saves weights to /checkpoints.

This is a demonstration-grade but real training run: modest epoch counts
(a few hundred) and dataset sizes (tens of thousands of samples) so the
whole pipeline runs to completion on CPU in a few minutes, while remaining
a genuine gradient-descent optimization exhibiting real loss decay.

Usage:
    python training/train.py
"""

