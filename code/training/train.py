def train_boris_corrector(train_data, val_data, epochs=EPOCHS):
    logger.info("=== Training Boris + Corrector ===")
    set_global_seed(SEED)
    model = build_bc().to(DEVICE)
    opt = torch.optim.Adam(model.parameters(), lr=LR_BC)

    # Precompute Boris predictions (numpy, fully vectorized) for the whole
    # training set -- the Boris step itself is not learned/differentiated.
    # NOTE: train_data here is the MULTI-SCALE dataset (dt in [0.02, 0.16])
    # so the corrector learns how the required correction scales with dt,
    # which is essential for it to generalize to the larger steps used in
    # the B4 decaying-field stress test (Figure 4).
    r_np, v_np, B_np, dt_np = train_data["r"], train_data["v"], train_data["B"], train_data["dt"]
    r_boris, v_boris = vectorized_boris_step(r_np, v_np, B_np, dt_np[:, 0])

    ds = TensorDataset(
        to_tensor(r_np), to_tensor(v_np), to_tensor(B_np), to_tensor(dt_np),
        to_tensor(r_boris), to_tensor(v_boris),
        to_tensor(train_data["r_next"]), to_tensor(train_data["v_next"]),
    )
    loader = DataLoader(ds, batch_size=BATCH_SIZE, shuffle=True)

    history = []
    for epoch in range(epochs):
        model.train()
        epoch_loss = 0.0
        n_batches = 0
        for r, v, B, dt, r_b, v_b, r_next, v_next in loader:
            opt.zero_grad()
            delta_r, delta_v = model(r, v, B, dt)
            loss, parts = model.physics_loss(r_b, v_b, delta_r, delta_v, r_next, v_next)
            loss.backward()
            opt.step()
            epoch_loss += loss.item()
            n_batches += 1
        avg_loss = epoch_loss / n_batches
        history.append(avg_loss)
        if epoch % 50 == 0 or epoch == epochs - 1:
            logger.info(f"[Boris+Corrector] epoch {epoch:4d}/{epochs}  loss={avg_loss:.6e}")
    return model, history


def main():
    set_global_seed(SEED)
    t0 = time.time()

    run_params = {
        "seed": SEED,
        "epochs": EPOCHS,
        "batch_size": BATCH_SIZE,
        "device": DEVICE,
        "train_fields": list(TRAIN_FIELDS.keys()),
        "lr_pinn": LR_PINN, "lr_hnn": LR_HNN, "lr_sympnet": LR_SYMP, "lr_boris_corrector": LR_BC,
    }
    log_run_params(logger, run_params)

    logger.info("Ensuring reference datasets exist ...")
    build_and_save_all(force=False)
    build_and_save_corrector_dataset(force=False)

    logger.info("Loading combined training/validation data ...")
    train_data = load_combined_dataset("train")
    val_data = load_combined_dataset("val")
    logger.info(f"Train samples: {train_data['r'].shape[0]}, Val samples: {val_data['r'].shape[0]}")

    corrector_train_data = load_corrector_dataset("train")
    logger.info(f"Boris+Corrector multi-scale train samples: {corrector_train_data['r'].shape[0]}")

    histories = {}

    model_pinn, hist_pinn = train_pinn(train_data, val_data)
    torch.save(model_pinn.state_dict(), os.path.join(CHECKPOINT_DIR, "pinn_symplectic.pt"))
    histories["pinn_symplectic"] = hist_pinn

    model_hnn, hist_hnn = train_hnn(train_data, val_data)
    torch.save(model_hnn.state_dict(), os.path.join(CHECKPOINT_DIR, "hnn.pt"))
    histories["hnn"] = hist_hnn

    model_symp, hist_symp = train_sympnet(train_data, val_data)
    torch.save(model_symp.state_dict(), os.path.join(CHECKPOINT_DIR, "sympnet.pt"))
    histories["sympnet"] = hist_symp

    model_bc, hist_bc = train_boris_corrector(corrector_train_data, val_data)
    torch.save(model_bc.state_dict(), os.path.join(CHECKPOINT_DIR, "boris_corrector.pt"))
    histories["boris_corrector"] = hist_bc

    with open(os.path.join(CHECKPOINT_DIR, "training_history.json"), "w") as f:
        json.dump(histories, f, indent=2)

    with open(os.path.join(CHECKPOINT_DIR, "run_params.json"), "w") as f:
        json.dump(run_params, f, indent=2)

    dt_elapsed = time.time() - t0
    logger.info(f"All models trained and saved to {CHECKPOINT_DIR}. "
                f"Total training time: {dt_elapsed:.1f} s")


if __name__ == "__main__":
    main()
