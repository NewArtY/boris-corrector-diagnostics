"""EA1: train the three external architectures at one training budget.

Writes ea1_training.json and ckpt/<arch>_r<rep>.npz.  Rerunning compares
against the committed JSON and exits non-zero on any disagreement.

    python ea1_train.py            train, then check against the committed file
    python ea1_train.py --force    overwrite the committed file
    python ea1_train.py --quick    a short smoke run, writes nothing

WHAT IS HELD EQUAL
------------------
Budget.  4400 Adam steps at batch 512 and lr 1e-3 under cosine annealing,
which is what training/train_corrector_b4.py spends on the learned corrector
(400 epochs over 5400 training samples).

Data.  One set of 6000 states sampled along fine Boris trajectories over the
five decay times of TAU_TRAIN, generated by the same procedure as
train_corrector_b4.py:build_dataset and shared by all three architectures at
each repetition.  What each architecture is asked to fit at those states
differs, because the architectures differ:

  HNN      exact analytic (dq/dt, dp/dt) at the state.  Analytic derivatives
           rather than finite differences: the more generous of the two
           options Greydanus et al. describe.
  SympNet  the canonical state after exact propagation over one step h, taken
           from the same fine Boris reference the corrector was trained on.
  PINN     no label at all.  The midpoint residual of the equations of motion
           is evaluated at the state, which is what a physics-informed loss is.

Seeds.  Weight initialisation, minibatch shuffling and data generation draw
from three disjoint ledgers (`ea_common.seed_of`).  Data at repetition r is
identical across the three architectures and different across r, which is how
the corrector's five retrainings were done.  No generator is built inside a
loop, and no seed appears twice anywhere in this directory.

WHAT IS NOT HELD EQUAL, AND WHY IT CANNOT BE
--------------------------------------------
Parameter count.  The HNN and the PINN are dense networks of the same shape as
the corrector, 50,433 and 50,820 parameters against its 52,102.  A G-SympNet
cannot be made that large at a sensible width: its weight matrices have the
phase-space dimension, two, as one of their sides, so its parameter count
grows linearly rather than quadratically in the width.  At ten modules of
width 256 it holds 15,360 parameters.  Forcing 50,000 would mean a width near
850, which is not a size Jin et al. use.  Parameter count is therefore
reported, not equalised, and the capacity control below is the answer to the
objection that follows.

THE CONTROL THAT HAS TO BE THERE
--------------------------------
An earlier version of this work compared against three fully learned
integrators trained under a budget too small to converge, and the comparison
was worthless for that reason.  So two controls run beside the four
repetitions: four times the Adam steps at the same width, and twice the width
at the same number of Adam steps, one repetition each, with seeds from their
own ledger.  If the rollout error does not fall across those, the failure is
the architecture and not the budget.  If it does fall, the number to quote is
the one at the largest budget, and the report says so.
"""
