def to_stepper(arch, model, tau):
    if arch == "hnn":
        net = C.lift_torch_mlp(model.net, model.x_mean.numpy(),
                               model.x_std.numpy(), None)
        return A.HNNStepper(net, tau)
    if arch == "pinn":
        net = C.lift_torch_mlp(model.net, model.x_mean.numpy(),
                               model.x_std.numpy(), model.y_scale.numpy())
        return A.PINNStepper(net, tau)
    mods = []
    for i, kind in enumerate(model.kinds):
        mods.append((kind,
                     model.K[i].detach().numpy().copy(),
                     model.a0[i].detach().numpy().copy(),
                     model.a1[i].detach().numpy().copy(),
                     model.b0[i].detach().numpy().copy(),
                     model.b1[i].detach().numpy().copy()))
    return A.SympNetStepper(mods, tau)


def save_stepper(path, arch, model):
    d = {"arch": arch}
    if arch in ("hnn", "pinn"):
        st = to_stepper(arch, model, C.TAU_PAPER)
        for i, (W, b) in enumerate(zip(st.net.Ws, st.net.bs)):
            d["W%d" % i] = W
            d["b%d" % i] = b.ravel()
        d["x_mean"] = st.net.x_mean.ravel()
        d["x_std"] = st.net.x_std.ravel()
        d["y_scale"] = st.net.y_scale.ravel()
    else:
        st = to_stepper(arch, model, C.TAU_PAPER)
        d["kinds"] = np.array(model.kinds)
        for i, (_k, K, a0, a1, b0, b1) in enumerate(st.modules):
            d["K%d" % i] = K; d["a0_%d" % i] = a0; d["a1_%d" % i] = a1
            d["b0_%d" % i] = b0; d["b1_%d" % i] = b1
    np.savez(path, **d)


def load_stepper(path, tau):
    z = np.load(path, allow_pickle=False)
    arch = str(z["arch"])
    if arch in ("hnn", "pinn"):
        i = 0
        Ws, bs = [], []
        while ("W%d" % i) in z:
            Ws.append(z["W%d" % i]); bs.append(z["b%d" % i]); i += 1
        net = C.NumpyMLP(Ws, bs, z["x_mean"], z["x_std"], z["y_scale"])
        return A.HNNStepper(net, tau) if arch == "hnn" else A.PINNStepper(net, tau)
    kinds = [str(k) for k in z["kinds"]]
    mods = [(kinds[i], z["K%d" % i], z["a0_%d" % i], z["a1_%d" % i],
             z["b0_%d" % i], z["b1_%d" % i]) for i in range(len(kinds))]
    return A.SympNetStepper(mods, tau)


def score_section7(stepper, tau=C.TAU_PAPER, dt=C.DT, t_final=C.T_FINAL):
    """The two channels of Table 1: trajectory error in Larmor radii and the
    median relative energy error over the second half of the run, scored
    against DOP853 at rtol 1e-12 and atol 1e-14 on the same grid."""
    n = int(round(t_final / dt))
    ts = (np.arange(n + 1)) * dt
    r_ref, v_ref = C.dop853(tau, ts)
    x = np.array([C.R0[0]]); y = np.array([C.R0[1]])
    vx = np.array([C.V0[0]]); vy = np.array([C.V0[1]])
    rs = np.empty((n + 1, 2)); vs = np.empty((n + 1, 2))
    rs[0] = [x[0], y[0]]; vs[0] = [vx[0], vy[0]]
    t = 0.0
    for i in range(n):
        x, y, vx, vy = stepper.step(x, y, vx, vy, t, dt)
        t += dt
        rs[i + 1] = [x[0], y[0]]; vs[i + 1] = [vx[0], vy[0]]
        if not np.isfinite(vx[0]) or np.hypot(vx[0], vy[0]) > 1e3:
            return {"pos_err_rms": float("inf"), "energy_err_median_2nd_half":
                    float("inf"), "diverged_at_step": i + 1}
    e = C.energy(vs[:, 0], vs[:, 1])
    e_ref = C.energy(v_ref[:, 0], v_ref[:, 1])
    half = len(ts) // 2
    pos = np.linalg.norm(rs - r_ref, axis=1)
    return {"pos_err_rms": float(np.sqrt(np.mean(pos ** 2))),
            "pos_err_final": float(pos[-1]),
            "energy_err_median_2nd_half":
                float(np.median(np.abs(e - e_ref)[half:] / e_ref[0])),
            "energy_err_max": float(np.max(np.abs(e - e_ref) / e_ref[0])),
            "flops_per_step": int(stepper.flops_per_step()),
            "flops_run": int(stepper.flops_per_step() * n),
            "diverged_at_step": None}


