def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()
    steps = 120 if a.quick else C.ADAM_STEPS

    out = {"setup": {
        "problem": "planar charged particle, B_z = B0 exp(-t/tau), induced E, "
                   "q=-1, m=1, r0=(1,0), v0=(0,1), h=0.3 (Omega h = 0.3)",
        "tau_paper": C.TAU_PAPER, "tau_train": list(C.TAU_TRAIN),
        "budget_adam_steps": steps, "batch": C.BATCH, "lr": C.LR,
        "n_repetitions": N_REP,
        "corrector_reference": {"n_parameters": 52102,
                                "flops_per_forward": 113958,
                                "flops_per_corrector_step": 114091},
        "seed_ledger": "9e6 + 1e5*arch + 1e3*role + rep; arch 0 hnn, 1 sympnet, "
                       "2 pinn, 7 shared data; role 0 init, 1 shuffle, "
                       "2 collocation, 3 probe, 4 control",
    }, "runs": {}, "controls": {}}

    # calibration of the flop model against the figure Section 9 prints
    assert C.mlp_forward_flops([13, 128, 128, 128, 128, 6]) == 113958, \
        "flop model no longer reproduces the 113,958 of Section 9"

    data_cache = {}
    for rep in range(N_REP):
        t0 = time.time()
        data_cache[rep] = canonicalise(build_states(rep))
        print("data rep%d  %d states  %.1fs" % (rep, data_cache[rep]["x"].size,
                                                time.time() - t0), flush=True)

    for arch in ("sympnet", "pinn", "hnn"):
        for rep in range(N_REP):
            model, info = train_one(arch, rep, data_cache[rep], steps=steps)
            st = to_stepper(arch, model, C.TAU_PAPER)
            info.update(score_section7(st))
            info["omega_h_measured"] = A.measure_scheme_frequency(st)
            out["runs"]["%s/rep%d" % (arch, rep)] = info
            if not a.quick:
                save_stepper(os.path.join(CKPT, "%s_r%d.npz" % (arch, rep)),
                             arch, model)
            print("  -> %-8s rep%d  traj %.4e  energy %.4e  flops/step %d  "
                  "omega_h %.6f"
                  % (arch, rep, info["pos_err_rms"],
                     info["energy_err_median_2nd_half"], info["flops_per_step"],
                     info["omega_h_measured"]), flush=True)

    # ---- the budget and capacity control ------------------------------
    if not a.quick:
        for arch in ("sympnet", "pinn", "hnn"):
            for k, (mult, wid, snw) in enumerate(
                    ((4, HID, SN_WIDTH), (1, 2 * HID, 2 * SN_WIDTH))):
                model, info = train_one(arch, k, data_cache[0],
                                        steps=mult * C.ADAM_STEPS, width=wid,
                                        sn_width=snw, role="control")
                st = to_stepper(arch, model, C.TAU_PAPER)
                info.update(score_section7(st))
                info["budget_multiplier"] = mult
                info["width"] = snw if arch == "sympnet" else wid
                out["controls"]["%s/x%d_w%d" % (arch, mult, info["width"])] = info
                print("  ctl %-8s x%-2d w%-4d traj %.4e energy %.4e"
                      % (arch, mult, info["width"], info["pos_err_rms"],
                         info["energy_err_median_2nd_half"]), flush=True)

    # boris and the classical reference rows, for the same two channels
    out["reference_rows"] = {}
    bs = A.BorisStepper(C.TAU_PAPER)
    out["reference_rows"]["boris"] = score_section7(bs)
    out["reference_rows"]["boris"]["omega_h_measured"] = \
        A.measure_scheme_frequency(bs)
    out["reference_rows"]["boris"]["omega_h_closed_form"] = \
        float(2 * np.arctan(C.DT / 2) / C.DT)

    if a.quick:
        print(json.dumps(out["runs"], indent=1)[:4000])
        return 0
    return C.check_or_write(OUT, out, rtol=1e-6, force=a.force)


