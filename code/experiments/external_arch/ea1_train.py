def build_states(rep):
    """6000 states along fine Boris trajectories, one draw per repetition.

    The procedure is train_corrector_b4.py:build_dataset with the third
    dimension removed: the same five decay times, the same three trajectories
    each, the same 400 coarse steps, the same radius window, and the reference
    propagation over one coarse step taken as 150 Boris steps of h/150.
    """
    rng = np.random.default_rng(C.seed_of(DATA_ARCH_SLOT, C.ROLE["collocation"], rep))
    rows = []
    n_coarse = int(round(C.T_FINAL / C.DT))
    dt_fine = C.DT / 150.0
    for tau in C.TAU_TRAIN:
        for _k in range(N_TRAJ := C.N_TRAJ_PER_TAU):
            rho = C.RHO_RANGE[0] + (C.RHO_RANGE[1] - C.RHO_RANGE[0]) * rng.random()
            phase = 2 * np.pi * rng.random()
            x, y = rho * np.cos(phase), rho * np.sin(phase)
            vx, vy = -np.sin(phase), np.cos(phase)
            t = 0.0
            for _n in range(n_coarse):
                xf, yf, vxf, vyf, tf = x, y, vx, vy, t
                for _m in range(150):
                    xf, yf, vxf, vyf = C.boris_plane(xf, yf, vxf, vyf, tf, tau, dt_fine)
                    tf += dt_fine
                rows.append((x, y, vx, vy, C.bz(t, tau), tau, t,
                             xf, yf, vxf, vyf))
                x, y, vx, vy = xf, yf, vxf, vyf
                t += C.DT
    a = np.asarray(rows, dtype=float)
    return {"x": a[:, 0], "y": a[:, 1], "vx": a[:, 2], "vy": a[:, 3],
            "s": a[:, 4], "tau": a[:, 5], "t": a[:, 6],
            "xn": a[:, 7], "yn": a[:, 8], "vxn": a[:, 9], "vyn": a[:, 10]}


def canonicalise(d):
    """Add the canonical coordinates and the exact canonical time derivatives."""
    ax, ay = C.vecpot(d["x"], d["y"], d["t"], d["tau"])
    d["px"] = d["vx"] - ax
    d["py"] = d["vy"] - ay
    axn, ayn = C.vecpot(d["xn"], d["yn"], d["t"] + C.DT, d["tau"])
    d["pxn"] = d["vxn"] - axn
    d["pyn"] = d["vyn"] - ayn
    # dq/dt = v ; dp/dt = -(grad A)^T v = -(B_z/2)(v_y, -v_x)
    d["dqx"] = d["vx"]
    d["dqy"] = d["vy"]
    half_b = 0.5 * d["s"]
    d["dpx"] = -half_b * d["vy"]
    d["dpy"] = +half_b * d["vx"]
    return d


# =====================================================================
#  torch models
# =====================================================================
def mlp(n_in, n_out, hidden, n_layers, gen, last_scale=1e-3):
    layers = [torch.nn.Linear(n_in, hidden), torch.nn.Tanh()]
    for _ in range(n_layers - 1):
        layers += [torch.nn.Linear(hidden, hidden), torch.nn.Tanh()]
    layers += [torch.nn.Linear(hidden, n_out)]
    seq = torch.nn.Sequential(*layers)
    for m in seq:
        if isinstance(m, torch.nn.Linear):
            bound = 1.0 / np.sqrt(m.in_features)
            with torch.no_grad():
                m.weight.uniform_(-bound, bound, generator=gen)
                m.bias.uniform_(-bound, bound, generator=gen)
    with torch.no_grad():
        seq[-1].weight.uniform_(-last_scale, last_scale, generator=gen)
        seq[-1].bias.zero_()
    return seq


class HNNTorch(torch.nn.Module):
    def __init__(self, gen, hidden=HID, n_layers=NLAY):
        super().__init__()
        self.net = mlp(5, 1, hidden, n_layers, gen, last_scale=1e-2)
        self.register_buffer("x_mean", torch.zeros(5))
        self.register_buffer("x_std", torch.ones(5))

    def H(self, z):
        return self.net((z - self.x_mean) / self.x_std).squeeze(-1)

    def field(self, z):
        z = z.clone().requires_grad_(True)
        g, = torch.autograd.grad(self.H(z).sum(), z, create_graph=self.training)
        return torch.stack([g[:, 2], g[:, 3], -g[:, 0], -g[:, 1]], dim=1)


class SympNetTorch(torch.nn.Module):
    """G-SympNet, Jin et al. Eq. (11), with parameters affine in B_z."""

    def __init__(self, gen, n_modules=SN_MODULES, width=SN_WIDTH):
        super().__init__()
        self.kinds = ["up" if i % 2 == 0 else "low" for i in range(n_modules)]
        self.K = torch.nn.ParameterList()
        self.a0 = torch.nn.ParameterList(); self.a1 = torch.nn.ParameterList()
        self.b0 = torch.nn.ParameterList(); self.b1 = torch.nn.ParameterList()
        for _ in range(n_modules):
            K = torch.empty(width, 2)
            K.uniform_(-1.0, 1.0, generator=gen)
            self.K.append(torch.nn.Parameter(K))
            a = torch.empty(width); a.uniform_(-1e-2, 1e-2, generator=gen)
            self.a0.append(torch.nn.Parameter(a))
            self.a1.append(torch.nn.Parameter(torch.zeros(width)))
            b = torch.empty(width); b.uniform_(-1.0, 1.0, generator=gen)
            self.b0.append(torch.nn.Parameter(b))
            self.b1.append(torch.nn.Parameter(torch.zeros(width)))

    def forward(self, q, p, s):
        for i, kind in enumerate(self.kinds):
            a = self.a0[i] + s[:, None] * self.a1[i]
            b = self.b0[i] + s[:, None] * self.b1[i]
            if kind == "up":
                p = p + torch.tanh(q @ self.K[i].T + b).mul(a) @ self.K[i]
            else:
                q = q + torch.tanh(p @ self.K[i].T + b).mul(a) @ self.K[i]
        return q, p


class PINNTorch(torch.nn.Module):
    def __init__(self, gen, hidden=HID, n_layers=NLAY):
        super().__init__()
        self.net = mlp(5, 4, hidden, n_layers, gen, last_scale=1e-3)
        self.register_buffer("x_mean", torch.zeros(5))
        self.register_buffer("x_std", torch.ones(5))
        self.register_buffer("y_scale", torch.ones(4))

    def forward(self, z):
        return self.net((z - self.x_mean) / self.x_std) * self.y_scale


# =====================================================================
#  losses
# =====================================================================
def hnn_loss(model, z, tgt):
    f = model.field(z)
    return ((f - tgt) ** 2).mean()


def sympnet_loss(model, q, p, s, qn, pn, scale):
    q2, p2 = model(q, p, s)
    return (((q2 - qn) ** 2).sum(1) + ((p2 - pn) ** 2).sum(1)).mean() / scale


def pinn_residual(model, z, tau_t, dt):
    """Midpoint residual of the equations of motion on the predicted map."""
    d = model(z)
    x, y, vx, vy = z[:, 0], z[:, 1], z[:, 2], z[:, 3]
    xn, yn = x + d[:, 0], y + d[:, 1]
    vxn, vyn = vx + d[:, 2], vy + d[:, 3]
    xm, ym = 0.5 * (x + xn), 0.5 * (y + yn)
    vxm, vym = 0.5 * (vx + vxn), 0.5 * (vy + vyn)
    tau, t = tau_t[:, 0], tau_t[:, 1]
    bm = torch.exp(-(t + 0.5 * dt) / tau)
    hb = 0.5 * bm / tau
    exm, eym = -hb * ym, hb * xm
    axm = C.Q * (exm + vym * bm)
    aym = C.Q * (eym - vxm * bm)
    rr = ((xn - x) / dt - vxm) ** 2 + ((yn - y) / dt - vym) ** 2
    rv = ((vxn - vx) / dt - axm) ** 2 + ((vyn - vy) / dt - aym) ** 2
    return rr.mean() + rv.mean()


def pinn_symplectic_penalty(model, z, tau_t, dt):
    """||J^T Omega J - Omega||_F^2 for the map in canonical coordinates.

    The canonical state is (x, y, p_x, p_y) with p = v - A(r,t); the network
    works in (x, y, v_x, v_y), so the Jacobian is conjugated by the constant
    (at fixed t) linear map v <-> p on both sides.
    """
    n = z.shape[0]
    tau, t = tau_t[:, 0], tau_t[:, 1]
    b_in = torch.exp(-t / tau)
    b_out = torch.exp(-(t + dt) / tau)

    def canon_map(w):
        # w = (x, y, px, py) -> canonical output
        x, y = w[:, 0], w[:, 1]
        vx = w[:, 2] - 0.5 * b_in * (-y)
        vy = w[:, 3] - 0.5 * b_in * x
        zz = torch.stack([x, y, vx, vy, b_in], dim=1)
        d = model(zz)
        xn, yn = x + d[:, 0], y + d[:, 1]
        vxn, vyn = vx + d[:, 2], vy + d[:, 3]
        pxn = vxn + 0.5 * b_out * (-yn)
        pyn = vyn - 0.5 * b_out * xn
        return torch.stack([xn, yn, pxn, pyn], dim=1)

    x, y, vx, vy = z[:, 0], z[:, 1], z[:, 2], z[:, 3]
    px = vx + 0.5 * b_in * (-y)
    py = vy - 0.5 * b_in * x
    w = torch.stack([x, y, px, py], dim=1)
    cols = []
    for k in range(4):
        e = torch.zeros(n, 4)
        e[:, k] = 1.0
        _, jvp = torch.func.jvp(canon_map, (w,), (e,))
        cols.append(jvp)
    J = torch.stack(cols, dim=2)                       # (n, out, in)
    Om = torch.zeros(4, 4)
    Om[0, 2] = Om[1, 3] = 1.0
    Om[2, 0] = Om[3, 1] = -1.0
    R = J.transpose(1, 2) @ Om @ J - Om
    return (R ** 2).sum(dim=(1, 2)).mean()


# =====================================================================
#  training driver
# =====================================================================
def train_one(arch, rep, data, steps=C.ADAM_STEPS, width=HID, sn_width=SN_WIDTH,
              role="init", verbose=True):
    ai = C.ARCH_INDEX[arch]
    role_i = C.ROLE[role]
    s_init = C.seed_of(ai, role_i, rep)
    s_shuf = C.seed_of(ai, C.ROLE["shuffle"] if role == "init" else role_i, rep + 500)
    gen = torch.Generator().manual_seed(s_init)
    shuffler = np.random.default_rng(s_shuf)      # built once, outside the loop

    n = data["x"].size
    tt = lambda k: torch.tensor(data[k])          # noqa: E731

    if arch == "hnn":
        z = torch.stack([tt("x"), tt("y"), tt("px"), tt("py"), tt("s")], dim=1)
        tgt = torch.stack([tt("dqx"), tt("dqy"), tt("dpx"), tt("dpy")], dim=1)
        model = HNNTorch(gen, hidden=width)
        with torch.no_grad():
            model.x_mean.copy_(z.mean(0))
            model.x_std.copy_(z.std(0).clamp_min(1e-12))
        loss_fn = lambda b: hnn_loss(model, z[b], tgt[b])          # noqa: E731
    elif arch == "sympnet":
        q = torch.stack([tt("x"), tt("y")], dim=1)
        p = torch.stack([tt("px"), tt("py")], dim=1)
        qn = torch.stack([tt("xn"), tt("yn")], dim=1)
        pn = torch.stack([tt("pxn"), tt("pyn")], dim=1)
        s = tt("s")
        scale = float((((qn - q) ** 2).sum(1) + ((pn - p) ** 2).sum(1)).mean())
        model = SympNetTorch(gen, width=sn_width)
        loss_fn = lambda b: sympnet_loss(model, q[b], p[b], s[b], qn[b], pn[b],
                                         scale)                     # noqa: E731
    elif arch == "pinn":
        z = torch.stack([tt("x"), tt("y"), tt("vx"), tt("vy"), tt("s")], dim=1)
        tau_t = torch.stack([tt("tau"), tt("t")], dim=1)
        model = PINNTorch(gen, hidden=width)
        with torch.no_grad():
            model.x_mean.copy_(z.mean(0))
            model.x_std.copy_(z.std(0).clamp_min(1e-12))
            dr = torch.stack([tt("xn") - tt("x"), tt("yn") - tt("y"),
                              tt("vxn") - tt("vx"), tt("vyn") - tt("vy")], dim=1)
            model.y_scale.copy_(dr.abs().mean(0).clamp_min(1e-16))

        def loss_fn(b):
            r = pinn_residual(model, z[b], tau_t[b], C.DT)
            sub = b[:SYMP_SUBSAMPLE]
            pen = pinn_symplectic_penalty(model, z[sub], tau_t[sub], C.DT)
            return r + LAMBDA_SYMP * pen
    else:
        raise ValueError(arch)

    opt = torch.optim.Adam(model.parameters(), lr=C.LR)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=steps)
    hist = []
    t0 = time.time()
    for it in range(steps):
        b = torch.from_numpy(shuffler.integers(0, n, size=C.BATCH))
        loss = loss_fn(b)
        opt.zero_grad()
        loss.backward()
        opt.step()
        sched.step()
        if it % max(1, steps // 10) == 0 or it == steps - 1:
            hist.append((it, float(loss.item())))
            if verbose:
                print("   %-8s rep%d  it %5d  loss %.6e  %5.1fs"
                      % (arch, rep, it, float(loss.item()), time.time() - t0),
                      flush=True)
    n_par = sum(p_.numel() for p_ in model.parameters())
    return model, {"seed_init": s_init, "seed_shuffle": s_shuf,
                   "adam_steps": steps, "batch": C.BATCH, "lr": C.LR,
                   "n_parameters": n_par, "loss_history": hist,
                   "final_loss": hist[-1][1], "train_seconds": time.time() - t0}


# =====================================================================
